  function filteredNews() {
    const f = state.news;
    const q = f.q.trim().toLowerCase();
    const list = state.run.articles.filter(
      (a) =>
        (!f.keyword || a.keywords.includes(f.keyword)) &&
        (!f.source || a.source === f.source) &&
        (!f.hotOnly || a.super_hot.length > 0) &&
        (!q ||
          `${a.title} ${a.description} ${a.source} ${a.author || ""}`
            .toLowerCase()
            .includes(q)),
    );
    const t = (iso) => Date.parse(iso) || 0;
    if (f.sort === "newest")
      list.sort((a, b) => t(b.published_at) - t(a.published_at));
    else if (f.sort === "oldest")
      list.sort((a, b) => t(a.published_at) - t(b.published_at));
    else if (f.sort === "source")
      list.sort(
        (a, b) =>
          a.source.localeCompare(b.source) ||
          t(b.published_at) - t(a.published_at),
      );
    return list;
  }

