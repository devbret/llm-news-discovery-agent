  async function sendChat(text) {
    const input = $("#chat-input");
    const content = (text !== undefined ? text : input.value).trim();
    if (!content || state.chat.busy || !state.run) return;
    input.value = "";
    input.style.height = "";
    const runId = state.runId;
    const history = state.chat.messages
      .filter((m) => !m.error && !m.streaming)
      .map((m) => ({ role: m.role, content: m.content }));
    history.push({ role: "user", content });
    state.chat.messages.push({ role: "user", content });
    const assistant = { role: "assistant", content: "", streaming: true };
    state.chat.messages.push(assistant);
    renderChat();
    state.chat.busy = true;
    setChatBusy(true);
    const ctrl = new AbortController();
    state.chat.abort = ctrl;
    try {
      await streamNdjson(
        "/api/chat",
        {
          run_id: runId,
          model: state.chat.model,
          messages: history,
          focus_ids: state.chat.focus.map((f) => f.id),
        },
        (ev) => {
          if (state.runId !== runId) return;
          if (ev.error) throw new Error(ev.error);
          if (ev.content) {
            assistant.content += ev.content;
            patchLastMessage();
          }
        },
        ctrl.signal,
      );
    } catch (e) {
      if (e.name === "AbortError") {
        assistant.content = assistant.content
          ? `${assistant.content}\n\n*(stopped)*`
          : "*(stopped)*";
      } else if (assistant.content) {
        assistant.content += `\n\n*(error: ${e.message})*`;
      } else {
        assistant.error = true;
        assistant.content = e.message;
      }
    } finally {
      assistant.streaming = false;
      if (state.runId === runId) {
        state.chat.busy = false;
        state.chat.abort = null;
        setChatBusy(false);
        renderChat();
        input.focus();
      }
    }
  }

  function addFocus(aid) {
    const a = state.run && state.run.articles[aid];
    if (!a) return;
    if (!state.chat.focus.some((f) => f.id === aid)) {
      if (state.chat.focus.length >= MAX_FOCUS) state.chat.focus.shift();
      state.chat.focus.push({ id: aid, title: a.title });
    }
    renderFocus();
    showView("chat");
    const input = $("#chat-input");
    if (!input.value.trim())
      input.value = `What is the significance of "${a.title}" and how does it relate to the rest of this run?`;
    input.focus();
  }

