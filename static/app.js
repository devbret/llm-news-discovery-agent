  function parseHash() {
    const p = new URLSearchParams(location.hash.slice(1));
    const run = (p.get("run") || "")
      .split(/[,+ ]/)
      .map((x) => x.trim())
      .filter(Boolean);
    return { run, view: p.get("view") };
  }

