  async function selectRuns(ids) {
    const next = normalizeIds(ids);
    if (!next.length) return;
    const viewId = next.join("+");
    state.runIds = next;
    state.runId = viewId;
    renderRunMenu();
    show($("#load-error"), false);
    const token = ++state.loadToken;
    setLoading(true);
    let run;
    try {
      run = await getJSON(`/api/runs/${encodeURIComponent(viewId)}`);
    } catch (e) {
      if (token !== state.loadToken) return;
      setLoading(false);
      state.run = null;
      show($("#run-header"), false);
      const box = $("#load-error");
      box.textContent = `Could not load the selected run(s): ${e.message}`;
      show(box, true);
      return;
    }
    if (token !== state.loadToken) return;
    setLoading(false);
    state.run = run;
    state.news = defaultNews();
    clearChat(true);
    renderAll();
    updateHash();
  }

