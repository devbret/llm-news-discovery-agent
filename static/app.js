  function normalizeIds(ids) {
    const known = new Set(state.runs.map((r) => r.run_id));
    return Array.from(new Set((ids || []).filter((id) => known.has(id)))).sort(
      (a, b) => Number(a) - Number(b),
    );
  }

  function runTag(ri) {
    const runs = state.run ? state.run.runs : [];
    const r = runs[ri];
    if (!r) return "";
    const dupes = runs.filter((x) => x.root_keyword === r.root_keyword).length;
    return dupes > 1
      ? `${r.root_keyword} (${fmtShort(r.started_at)})`
      : r.root_keyword;
  }

  function keywordLabel(k) {
    const dupes = state.run.keywords.filter(
      (x) => x.keyword.toLowerCase() === k.keyword.toLowerCase(),
    ).length;
    if (dupes <= 1) return k.keyword;
    const r = state.run.runs[k.run];
    const sameRoot =
      r && r.root_keyword.toLowerCase() === k.keyword.toLowerCase();
    return sameRoot
      ? `${k.keyword} (${fmtShort(r.started_at)})`
      : `${k.keyword} | ${runTag(k.run)}`;
  }

