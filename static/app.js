  async function generateSummary() {
    if (state.summaryRun === state.runId || !state.run) return;
    const runId = state.runId;
    const model = state.chat.model;
    const box = $("#summary-content");
    state.summaryRun = runId;
    $("#summary-btn").disabled = true;
    box.innerHTML = '<p class="muted">Thinking...</p>';
    let text = "";
    let ok = false;
    try {
      await streamNdjson(
        `/api/runs/${encodeURIComponent(runId)}/summary`,
        { model },
        (ev) => {
          if (state.runId !== runId) return;
          if (ev.error) throw new Error(ev.error);
          if (ev.content) {
            text += ev.content;
            box.innerHTML = renderMarkdown(text);
          }
          if (ev.done) ok = true;
        },
      );
      if (ok && state.runId === runId) {
        state.run.summary = {
          model,
          created_at: new Date().toISOString(),
          text,
        };
        const entry = state.runs.find((r) => r.run_id === runId);
        if (entry) entry.has_summary = true;
      }
    } catch (e) {
      if (state.runId === runId)
        box.innerHTML = `<p class="error-text">Could not generate the briefing: ${esc(e.message)}</p>`;
    } finally {
      if (state.summaryRun === runId) state.summaryRun = null;
      if (state.runId === runId) {
        if (ok) renderSummary();
        else $("#summary-btn").disabled = false;
      }
    }
  }

